"""发票解析工作流的 Prompt 模板（纯字符串，零逻辑）。"""

# LLM 结构化提取：OCR/文本层 → 关键字段（function_calling 强制输出 InvoiceInfo）
# 设计要点：
# - 明确"只提取、不臆造"：识别不出的字段必须留空，由校验节点标 needs_human_review
# - 显式说明常见 OCR 噪声（发票代码易与发票号码混淆、O/0 混淆），降低误提取
# - 日期/金额规范化规则写死，保证 JSON 输出可直接落库
INVOICE_EXTRACT_PROMPT = """你是一名发票信息提取器。下面是一张发票经 OCR/文本层提取后的原始文本，请从中提取关键字段。

字段定义：
- invoice_date: 开票日期，统一为 YYYY-MM-DD（如"2026年10月08日" → "2026-10-08"）
- amount: 价税合计金额，统一为纯数字（如"¥553.00" → 553.0；"1,280.50" → 1280.5）
- invoice_code: 发票代码，10 或 12 位数字。注意区分：发票代码≠发票号码（号码通常 8 位或 20 位），
  只提取标注为"发票代码"的那一串
- seller_name: 销售方名称，从"销售方名称："或"销方名称："标签后提取的开票企业完整全称
  （如"杭州云启科技有限公司"，不含标签前缀本身）

规则：
1. 只提取文本中明确存在的信息，严禁臆造或从常识补全。
2. 识别不出的字段留空字符串/0，不要编造。
3. OCR 常见噪声处理：数字 0 与字母 O 混淆时按发票号段规律判断；忽略页脚、校验码等无关行。
4. 若文本中同时出现多张发票信息，只提取第一张。

发票原始文本：
{ocr_text}
"""

# 校验通过后的用户可见摘要（仅用于确认回显，结构化数据在 structured_output）
INVOICE_RESULT_SUMMARY = """已解析发票信息：

| 字段 | 值 |
|---|---|
| 开票日期 | {invoice_date} |
| 价税合计 | ¥{amount} |
| 发票代码 | {invoice_code} |
| 销售方 | {seller_name} |
"""
